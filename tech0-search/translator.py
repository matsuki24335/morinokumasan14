def translate(owner_text: str) -> dict:
    text = _norm(owner_text)
    matches = {}

    for category, phrases in TRANSLATION_DICT.items():
        hit = [p for p in phrases if _norm(p) in text]
        if hit:
            matches[category] = hit

    ranked = sorted(matches.keys(), key=lambda c: len(matches[c]), reverse=True)
    return {"categories": ranked, "matches": matches}


